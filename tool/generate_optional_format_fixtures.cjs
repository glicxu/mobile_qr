// Development-only candidate evaluation; does not change production allowlists.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const bwip = require(path.join(root, '.dart_tool/barcode-fixture-generator/node_modules/bwip-js'));
if (bwip.BWIPJS_VERSION.split(' ')[0] !== '4.11.4') throw new Error('Expected bwip-js 4.11.4');
const check = process.argv.includes('--check');
function write(file, bytes) {
  if (check) {
    if (!fs.readFileSync(file).equals(Buffer.from(bytes))) throw new Error(`Fixture drift: ${file}`);
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, bytes);
  }
}
(async () => {
  const fixtures = [];
  const embedded = [];
  for (const [format, bcid] of [['dataMatrix', 'datamatrix'], ['pdf417', 'pdf417'], ['aztec', 'azteccode']]) {
    for (const [size, value] of [['short', '  KEEP-00123  '], ['long', 'DALI-CANDIDATE:'.repeat(15) + 'end']]) {
      const id = `${format}_${size}`;
      const options = { bcid, text: value, scale: 4, padding: 20, backgroundcolor: 'FFFFFF' };
      const png = await bwip.toBuffer(structuredClone(options));
      write(path.join(root, 'test/fixtures/optional_formats', `${id}.png`), png);
      const fixture = { id, format, value, generatorOptions: options,
        sha256: crypto.createHash('sha256').update(png).digest('hex') };
      fixtures.push(fixture);
      embedded.push({ ...fixture, pngBase64: png.toString('base64') });
    }
  }
  write(path.join(root, 'test/fixtures/optional_formats/manifest.json'), JSON.stringify({
    generator: 'bwip-js 4.11.4', fixtures,
  }, null, 2) + '\n');
  write(path.join(root, 'integration_test/optional_format_data.g.dart'),
    '// GENERATED by tool/generate_optional_format_fixtures.cjs. Test targets only.\n' +
    "const optionalFormatFixturesJson =\n    r'''" + JSON.stringify(embedded) + "''';\n");
  console.log(`${check ? 'Verified' : 'Generated'} ${fixtures.length} candidate fixtures.`);
})().catch(error => { console.error(error); process.exitCode = 1; });
