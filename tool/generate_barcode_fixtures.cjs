// Install the pinned development-only generator as documented in the fixture README.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const root = path.resolve(__dirname, '..');
const bwip = require(path.join(root, '.dart_tool/barcode-fixture-generator/node_modules/bwip-js'));
const version = '4.11.4';
if (bwip.BWIPJS_VERSION.split(' ')[0] !== version) throw new Error(`Expected bwip-js ${version}`);
const check = process.argv.includes('--check');
const directory = path.join(root, 'test/fixtures/barcodes');
const cases = [
  ['qr_url', 'qrCode', 'qrcode', 'https://example.com/qa'],
  ['qr_whitespace', 'qrCode', 'qrcode', '  exact payload\n'],
  ['upca_zero', 'upcA', 'upca', '012345678905'],
  ['upca_other', 'upcA', 'upca', '036000291452'],
  ['upce_example', 'upcE', 'upce', '04252614'],
  ['upce_other', 'upcE', 'upce', '01234565'],
  ['ean8_example', 'ean8', 'ean8', '96385074'],
  ['ean8_zero', 'ean8', 'ean8', '00000000'],
  ['ean13_upca_pair', 'ean13', 'ean13', '0012345678905'],
  ['ean13_book', 'ean13', 'ean13', '9780306406157'],
  ['code128_short', 'code128', 'code128', 'DALI-128'],
  ['code128_url', 'code128', 'code128', 'https://example.com/barcode'],
  ['code128_whitespace', 'code128', 'code128', '  KEEP ZERO 00123  '],
  ['code39_short', 'code39', 'code39', 'DALI39'],
  ['code39_long', 'code39', 'code39', 'ORDER-00123-ABC'],
  ['code93_short', 'code93', 'code93', 'DALI93'],
  ['code93_long', 'code93', 'code93', 'ORDER-0093/ABC'],
  ['codabar_short', 'codabar', 'rationalizedCodabar', 'A123456A'],
  ['codabar_long', 'codabar', 'rationalizedCodabar', 'B1234567890-12B'],
  ['itf14_zero', 'itf14', 'itf14', '10012345000017'],
  ['itf14_other', 'itf14', 'itf14', '12345678901231'],
];

function writeOrCheck(file, bytes) {
  if (check) {
    if (!fs.readFileSync(file).equals(Buffer.from(bytes))) {
      throw new Error(`Fixture drift: ${path.relative(root, file)}`);
    }
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, bytes);
  }
}

async function main() {
  const fixtures = [];
  for (const [id, format, bcid, value] of cases) {
    const options = {
      bcid, text: value, scale: 3, padding: 16,
      backgroundcolor: 'FFFFFF', includetext: false,
      ...(format === 'qrCode' ? { eclevel: 'M' } : { height: 20 }),
      ...(format === 'code93' ? { includecheck: true } : {}),
    };
    const png = await bwip.toBuffer(structuredClone(options));
    writeOrCheck(path.join(directory, `${id}.png`), png);
    // UPC-A may be reported as zero-prefixed EAN-13 by native platforms.
    // These are explicit decoder representations, never app-side normalization.
    const expected = format === 'upcA'
      ? [{ format, value }, { format: 'ean13', value: `0${value}` }]
      : format === 'ean13' && value.startsWith('0')
        ? [{ format, value }, { format: 'upcA', value: value.slice(1) }]
        : [{ format, value }];
    fixtures.push({
      id, file: `${id}.png`, symbolFormat: format, encodedValue: value,
      expectedNativeResults: { android: expected, ios: expected },
      nativeExpectationStatus: 'provisional; verify on physical devices',
      generatorOptions: options,
      sha256: crypto.createHash('sha256').update(png).digest('hex'),
    });
  }
  writeOrCheck(path.join(directory, 'manifest.json'), `${JSON.stringify({
    schemaVersion: 1,
    generator: { name: 'bwip-js', version, source: 'https://github.com/metafloor/bwip-js' },
    fixtures,
  }, null, 2)}\n`);
  // Embed images only into the integration-test build, never production assets.
  const embedded = fixtures.map(fixture => ({
    ...fixture, pngBase64: fs.readFileSync(path.join(directory, fixture.file)).toString('base64'),
  }));
  writeOrCheck(path.join(root, 'integration_test/barcode_fixture_data.g.dart'),
    '// GENERATED by tool/generate_barcode_fixtures.cjs. Do not edit.\n' +
    '// Fixture images are compiled only into integration-test targets.\n' +
    "const scannerFixturesJson =\n    r'''" + JSON.stringify(embedded) + "''';\n");
  console.log(`${check ? 'Verified' : 'Generated'} ${fixtures.length} barcode fixtures.`);
}

main().catch(error => { console.error(error); process.exitCode = 1; });
